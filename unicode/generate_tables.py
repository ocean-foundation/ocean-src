#!/usr/bin/env python3
"""Regenerate unicode/tables.oc from Python's unicodedata module.

Run with a Python whose unicodedata.unidata_version is the intended Unicode
version: python3 unicode/generate_tables.py > unicode/tables.oc
Identifier tables are copied from the compiler so that IsIdentStart and
IsIdentContinue match the language's identifier rules exactly.
"""
import sys
import unicodedata

MAX = 0x110000
WHITE_SPACE = [0x9, 0xA, 0xB, 0xC, 0xD, 0x20, 0x85, 0xA0, 0x1680] + list(range(0x2000, 0x200B)) + [0x2028, 0x2029, 0x202F, 0x205F, 0x3000]


def ranges(predicate):
    out, start = [], None
    for c in range(MAX):
        if predicate(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def category(prefixes):
    return lambda c: unicodedata.category(chr(c)).startswith(prefixes)


def simple(c, method):
    if c == 0x130 and method == "lower":
        return 0x69
    mapped = getattr(chr(c), method)()
    return ord(mapped) if len(mapped) == 1 else c


def case_table(method):
    # (lo, hi, stride, delta): every stride-th code point from lo to hi maps by delta.
    pairs = [(c, simple(c, method) - c) for c in range(MAX) if 0xD800 > c or c > 0xDFFF if simple(c, method) != c]
    out = []
    for c, delta in pairs:
        if out:
            lo, hi, stride, d = out[-1]
            if d == delta and (c - hi == stride or (lo == hi and c - hi == 2)):
                out[-1] = (lo, c, c - hi if lo == hi else stride, d)
                continue
        out.append((c, c, 1, delta))
    return out


def emit(name, values, per_line=16):
    print(f"{name}: []int = {{")
    for i in range(0, len(values), per_line):
        print("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    print("};")


def flat(rs):
    return [v for r in rs for v in r]


def compiler_table(source, name):
    text = open(source).read()
    start = text.index(name + ": []int = {")
    end = text.index("};", start)
    return text[start:end + 2]


def main():
    compiler = sys.argv[1] if len(sys.argv) > 1 else "../ocean/compiler/scanner/unicode.oc"
    print("package unicode;")
    print()
    print(f"// Generated by generate_tables.py from Unicode {unicodedata.unidata_version}; do not edit.")
    print("// Range tables are flattened inclusive [lo, hi] pairs; case tables are")
    print("// [lo, hi, stride, delta] groups.")
    print()
    for name, prefixes in [("letterRanges", ("L",)), ("upperRanges", ("Lu",)), ("lowerRanges", ("Ll",)),
                           ("titleRanges", ("Lt",)), ("digitRanges", ("Nd",)), ("numberRanges", ("N",)),
                           ("punctRanges", ("P",)), ("symbolRanges", ("S",)), ("markRanges", ("M",)),
                           ("controlRanges", ("Cc",))]:
        emit(name, flat(ranges(category(prefixes))))
    emit("spaceRanges", flat(ranges(lambda c: c in WHITE_SPACE)))
    emit("toUpperTable", flat(case_table("upper")))
    emit("toLowerTable", flat(case_table("lower")))
    print("// Identifier tables copied from the compiler's scanner (XID_Start/XID_Continue).")
    print(compiler_table(compiler, "startRanges").replace("startRanges", "identStartRanges", 1))
    print(compiler_table(compiler, "continueRanges").replace("continueRanges", "identContinueRanges", 1))


main()
