#!/usr/bin/env python3
"""Regenerate unicode/tables.oc from the official Unicode character database.

Give the Unicode version and the matching UnicodeData.txt file as arguments.
Identifier tables are copied from the compiler so that IsIdentStart and
IsIdentContinue match the language's identifier rules exactly.
"""
import argparse
from pathlib import Path

MAX = 0x110000
WHITE_SPACE = [0x9, 0xA, 0xB, 0xC, 0xD, 0x20, 0x85, 0xA0, 0x1680] + list(range(0x2000, 0x200B)) + [0x2028, 0x2029, 0x202F, 0x205F, 0x3000]


def ranges(predicate):
    out, start = [], None
    for c in range(MAX):
        if predicate(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def read_unicode_data(source):
    categories = ["Cn"] * MAX
    upper, lower = {}, {}
    start = None
    for line in source.read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        code = int(fields[0], 16)
        name, category = fields[1:3]
        if name.endswith(", First>"):
            start = code
        elif name.endswith(", Last>"):
            categories[start:code + 1] = [category] * (code + 1 - start)
        else:
            categories[code] = category
        if fields[12]:
            upper[code] = int(fields[12], 16)
        if fields[13]:
            lower[code] = int(fields[13], 16)
    return categories, upper, lower


def case_table(mapping):
    # (lo, hi, stride, delta): every stride-th code point from lo to hi maps by delta.
    pairs = sorted((code, mapped - code) for code, mapped in mapping.items())
    out = []
    for c, delta in pairs:
        if out:
            lo, hi, stride, d = out[-1]
            if d == delta and (c - hi == stride or (lo == hi and c - hi == 2)):
                out[-1] = (lo, c, c - hi if lo == hi else stride, d)
                continue
        out.append((c, c, 1, delta))
    return out


def emit(name, values, per_line=16):
    print(f"{name}: []int = {{")
    for i in range(0, len(values), per_line):
        print("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    print("};")


def flat(rs):
    return [v for r in rs for v in r]


def compiler_table(source, name):
    text = open(source).read()
    start = text.index(name + ": []int = {")
    end = text.index("};", start)
    return text[start:end + 2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("version", help="Unicode version of UnicodeData.txt")
    parser.add_argument("unicode_data", type=Path)
    parser.add_argument("compiler", nargs="?", default="../ocean/compiler/scanner/unicode.oc")
    args = parser.parse_args()
    categories, upper, lower = read_unicode_data(args.unicode_data)
    print("package unicode;")
    print()
    print(f"// Generated by generate_tables.py from Unicode {args.version}; do not edit.")
    print("// Range tables are flattened inclusive [lo, hi] pairs; case tables are")
    print("// [lo, hi, stride, delta] groups.")
    print()
    for name, prefixes in [("letterRanges", ("L",)), ("upperRanges", ("Lu",)), ("lowerRanges", ("Ll",)),
                           ("titleRanges", ("Lt",)), ("digitRanges", ("Nd",)), ("numberRanges", ("N",)),
                           ("punctRanges", ("P",)), ("symbolRanges", ("S",)), ("markRanges", ("M",)),
                           ("controlRanges", ("Cc",))]:
        emit(name, flat(ranges(lambda c: categories[c].startswith(prefixes))))
    emit("spaceRanges", flat(ranges(lambda c: c in WHITE_SPACE)))
    emit("toUpperTable", flat(case_table(upper)))
    emit("toLowerTable", flat(case_table(lower)))
    print("// Identifier tables copied from the compiler's scanner (XID_Start/XID_Continue).")
    print(compiler_table(args.compiler, "startRanges").replace("startRanges", "identStartRanges", 1))
    print(compiler_table(args.compiler, "continueRanges").replace("continueRanges", "identContinueRanges", 1))


main()
